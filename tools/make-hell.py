#!/usr/bin/env python3
"""Generates docs/app/hell.css (light theme "Hell") from app.css by converting the dark colours. Run after CSS changes."""
import re, colorsys, sys, tinycss2
SRC = "/home/claude/moneycompass/docs/app/app.css"; OUT = "/home/claude/moneycompass/docs/app/hell.css"
PFX = ':root[data-theme="hell"] '
COL = re.compile(r'#[0-9a-fA-F]{8}\b|#[0-9a-fA-F]{6}\b|#[0-9a-fA-F]{3}\b|rgba?\([^)]*\)')
def parse(c):
    if c.startswith("#"):
        h = c[1:]
        if len(h) == 3: h = "".join(x*2 for x in h)
        r, g, b = (int(h[i:i+2], 16) for i in (0, 2, 4)); a = int(h[6:8], 16)/255 if len(h) == 8 else 1
    else:
        n = [float(x) for x in re.findall(r'[\d.]+', c)]
        r, g, b = n[:3]; a = n[3] if len(n) > 3 else 1
    return r, g, b, a
def hls(c):
    r, g, b, a = parse(c); h, l, s = colorsys.rgb_to_hls(r/255, g/255, b/255); return h, l, s, a
def out(h, l, s, a):
    r, g, b = colorsys.hls_to_rgb(h, max(0, min(1, l)), s)
    return f"rgba({round(r*255)},{round(g*255)},{round(b*255)},{round(a,3)})" if a < 1 else "#%02x%02x%02x" % (round(r*255), round(g*255), round(b*255))
def saturated(c): h, l, s, a = hls(c); return s > .45 and .25 < l < .78 and a > .5
SEL=""
def conv(c, kind):
    h, l, s, a = hls(c)
    if kind == "shadow":
        if s < .3 and l < .2: return out(h, l, s, a * .3)   # dark shadow -> soft
        return c                                              # glow stays
    if kind == "bg":
        if s > .45 and .25 < l < .85: return c               # brand colour stays
        if a < 1 and l > .85:
            if a <= .06 and re.search(r"card|\.ovh|\.ov-|panel|\.box", SEL): return "#EEF2F0"
            return out(.45, .12, .25, a * .9)  # white overlay -> dark overlay
        if l < .55:
            if a < .5: return c if s > .3 else out(h, l, s, a * .5)
            return out(h, min(1, .90 + l * .6), min(s, .25), a)
        return c
    if kind == "border":
        if a < 1 and l > .85: return out(.45, .12, .25, a * 1.3 if a < .3 else a)
        if l < .3 and a >= 1: return out(h, .86, min(s, .2), a)
        return c
    if kind == "text":
        if l > .55:
            if s > .45: return out(h, min(l, .33), s, a)    # green/yellow text darker
            return out(.45, 1 - l, min(s, .2) + .05, a)
        return c
    return c
BG = re.compile(r'^(background(-color|-image)?)$'); BD = re.compile(r'^(border(-top|-bottom|-left|-right)?(-color)?|outline(-color)?)$')
def convert_decl(name, value, keep_text):
    kind = "bg" if BG.match(name) else "border" if BD.match(name) else "text" if name in ("color", "fill", "stroke") else "shadow" if name == "box-shadow" else None
    if not kind or "var(" in value and not COL.search(value): return None
    if kind == "text" and keep_text: return None
    if name in ("fill", "stroke") and kind == "text": kind = "text"
    new = COL.sub(lambda m: conv(m.group(0), kind), value)
    return new if new != value else None
def rules(nodes, depth=0):
    res = []
    for n in nodes:
        if n.type == "qualified-rule":
            sel = tinycss2.serialize(n.prelude).strip()
            if "data-design" in sel and sel.startswith(":root[data-design") and sel.endswith("{"): pass
            decls = tinycss2.parse_declaration_list(n.content, skip_whitespace=True, skip_comments=True)
            ds = [d for d in decls if d.type == "declaration"]
            global SEL; SEL = sel
            keep_text = any(BG.match(d.lower_name) and any(saturated(c) for c in COL.findall(tinycss2.serialize(d.value))) for d in ds)
            new = []
            for d in ds:
                v = tinycss2.serialize(d.value).strip()
                nv = convert_decl(d.lower_name, v, keep_text)
                if nv: new.append(f"{d.lower_name}:{nv}{' !important' if d.important else ''}")
            if new:
                sels = [s.strip() for s in sel.split(",")]
                sels = [(":root[data-theme=\"hell\"]" + s[len(":root"):]) if s.startswith(":root[") else PFX + s for s in sels if s]
                res.append(("rule", ",".join(sels) + "{" + ";".join(new) + "}"))
        elif n.type == "at-rule" and n.lower_at_keyword == "media" and n.content:
            inner = rules(tinycss2.parse_rule_list(n.content, skip_whitespace=True, skip_comments=True))
            if inner: res.append(("media", "@media" + tinycss2.serialize(n.prelude) + "{" + "\n".join(x[1] for x in inner) + "}"))
    return res
css = open(SRC).read()
r = rules(tinycss2.parse_stylesheet(css, skip_whitespace=True, skip_comments=True))
head = '''/* GENERATED by tools/make-hell.py – light theme "Hell". Do not edit by hand. */
:root[data-theme="hell"]{color-scheme:light;--page:#CDD4D1;--card:#E1E6E3;--border:rgba(15,40,30,.14);--ink:#17251F;--muted:#44574F;--grid:rgba(15,40,30,.1);--primary:#0A8A5E;--good:#087A52;--warn:#B7791F;--bad:#D14343;--goals:#6D5BD0;--field:#EBEFED;--soft:#D9DFDC;--side:#D8DEDB;--hi:#0A8A5E;--hi2:#6D5BD0;--chip:rgba(15,40,30,.06)}
:root[data-theme="hell"] body{background:radial-gradient(1200px 700px at 85% 0%,#CBE8DC 0%,transparent 60%),radial-gradient(900px 600px at 0% 100%,#D3E6DD 0%,transparent 55%),var(--page)!important;color:var(--ink)}
'''
head += ':root[data-theme="hell"] select,:root[data-theme="hell"] input:not([type=checkbox]):not([type=radio]),:root[data-theme="hell"] textarea{background-color:#EBEFED;color:#17251F}\n'
_o = head + "\n".join(x[1] for x in r) + "\n" + open(__file__.replace("make-hell.py","hell-extra.css")).read()
for _a, _b in [("#EEF2F0", "#E1E6E3"), ("#F6F8F7", "#EBEFED"), ("#0e1714", "#17251F"), ("#12211C", "#17251F")]:
    _o = _o.replace(_a, _b).replace(_a.lower(), _b)
open(OUT, "w").write(_o)
print(len(r), "rules")
